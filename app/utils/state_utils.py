STATE_CODES = set(STATE_NAME_TO_CODE.values())


def normalize_state(state: str) -> str:
    cleaned_state = state.strip()

    if len(cleaned_state) == 2:
        code = cleaned_state.upper()

        if code in STATE_CODES:
            return code

    full_name = cleaned_state.lower()

    if full_name in STATE_NAME_TO_CODE:
        return STATE_NAME_TO_CODE[full_name]

    raise ValueError(f"Invalid state: {state}")